    def _geometry_has_holes(self, geom):
        """True if a QgsGeometry polygon/multipolygon has any interior ring."""
        if geom.isMultipart():
            for poly in geom.asMultiPolygon():
                if len(poly) > 1:  # exterior + >=1 interior ring
                    return True
            return False
        poly = geom.asPolygon()
        return bool(poly) and len(poly) > 1

