    def _build_expression_value(self, feature, layer, prefix, field1_name, field2_name, suffix, separator):
        """
        Build an ID from expression parts, joining non-empty parts with the separator.

        Parts: prefix, field1 value, field2 value, suffix.
        Empty/null parts are omitted (no double separators).
        """
        parts = []

        if prefix:
            parts.append(prefix)

        if field1_name:
            idx = layer.fields().indexFromName(field1_name)
            if idx != -1:
                val = feature.attributes()[idx]
                if val is not None and str(val) != "":
                    parts.append(str(val))

        if field2_name:
            idx = layer.fields().indexFromName(field2_name)
            if idx != -1:
                val = feature.attributes()[idx]
                if val is not None and str(val) != "":
                    parts.append(str(val))

        if suffix:
            parts.append(suffix)

        return separator.join(parts)

    def _build_output_fields(self, layer_fields, excluded_fields, extra_reserved=()):
        """
        Build the output QgsFields from the input layer fields plus TRACT fields.

        - Fields in `excluded_fields` are skipped (mapped to NodeID/PlotID via "Use existing field").
        - Fields whose name clashes with a TRACT field name, or with a name in
          `extra_reserved` (the land cover overlap fields when that check is on,
          SPEC-landcover-overlap FR-10), get an '_orig' suffix.
        - The four TRACT fields are always appended at the end.

        Returns:
            tuple[QgsFields, dict[str, str]]: (output fields, rename map {original_name: output_name})
        """
        out_fields = QgsFields()
        rename_map = {}
        reserved = set(TRACT_FIELD_NAMES) | set(extra_reserved)

        for field in layer_fields:
            name = field.name()

            if name in excluded_fields:
                continue

            if name in reserved:
                new_name = f"{name}_orig"
                rename_map[name] = new_name
                out_fields.append(QgsField(new_name, field.type()))
            else:
                out_fields.append(QgsField(name, field.type()))

        out_fields.append(QgsField("NodeID", STRING_FIELD_TYPE))
        out_fields.append(QgsField("PlotID", STRING_FIELD_TYPE))
        out_fields.append(QgsField("TRACTStatus", STRING_FIELD_TYPE))
        out_fields.append(QgsField("TRACTIssue", STRING_FIELD_TYPE))

        return out_fields, rename_map

    # Helper for after makeValid, to ensure we only keep polygonal parts if we end up with a GeometryCollection
    def _extract_polygonal_geometry(self, geom: QgsGeometry) -> QgsGeometry:
        """
        Ensure the geometry is polygonal.
        If makeValid() returns a GeometryCollection, extract polygon parts only.
        Returns an empty geometry if no polygonal part can be recovered.
        """
        if geom.isEmpty():
            return geom

        wkb_type = geom.wkbType()
        geom_type = QgsWkbTypes.geometryType(wkb_type)

        # Already polygonal
        if geom_type == QgsWkbTypes.GeometryType.PolygonGeometry:
            return geom

        # Try to extract polygon parts from geometry collections
        parts = []
        try:
            for part in geom.constParts():
                part_geom = QgsGeometry(part.clone())
                if QgsWkbTypes.geometryType(part_geom.wkbType()) == QgsWkbTypes.GeometryType.PolygonGeometry:
                    parts.append(part_geom)
        except Exception:
            return QgsGeometry()

        if not parts:
            return QgsGeometry()

        if len(parts) == 1:
            return parts[0]

        # Merge polygon parts into a multipolygon if possible
        collected = []
        for part_geom in parts:
            rings = self._polygon_rings_with_z(part_geom)
            if rings:
                collected.extend(rings)

        if not collected:
            return QgsGeometry()

        return self._build_polygon_geometry(collected, True)


    def _extract_polygon_rings(self, geom: QgsGeometry):
        """
        Helper for TRACT-style geometry checks that need to analyze individual rings.
        Returns polygon rings in normalized form:
        [
            [ring1, ring2, ...],   # polygon 1
            [ring1, ring2, ...],   # polygon 2
        ]
        """
        if geom.isEmpty():
            return []

        if geom.isMultipart():
            mp = geom.asMultiPolygon()
            return mp if mp else []
        else:
            poly = geom.asPolygon()
            return [poly] if poly else []


    def _has_duplicate_vertices_in_rings(self, geom: QgsGeometry) -> bool:
        """
        TRACT-style check:
        duplicate vertices anywhere in a ring, excluding the closing vertex.
        """
        polygon_rings = self._extract_polygon_rings(geom)

        for poly in polygon_rings:
            for ring in poly:
                if len(ring) < 2:
                    continue

                body = ring[:-1]  # exclude closing point
                coords = [(pt.x(), pt.y()) for pt in body]

                if len(set(coords)) < len(coords):
                    return True

        return False


    def _has_rings_with_fewer_than_three_unique_coords(self, geom: QgsGeometry) -> bool:
        """
        TRACT-style check:
        each ring must have at least 3 unique coordinates, excluding closing vertex.
        """
        polygon_rings = self._extract_polygon_rings(geom)

        for poly in polygon_rings:
            for ring in poly:
                if len(ring) < 2:
                    return True

                body = ring[:-1]
                uniq = {(pt.x(), pt.y()) for pt in body}

                if len(uniq) < 3:
                    return True

        return False


    def _has_boundary_self_intersections(self, geom: QgsGeometry) -> bool:
        """
        Exact TRACT-aligned check using Shapely:
        not sg.boundary.is_simple
        """
        if geom is None or geom.isEmpty():
            return False

        try:

            geojson_dict = json.loads(geom.asJson())
            sg = shape(geojson_dict)

            return not sg.boundary.is_simple

        except Exception as e:
            self._log(f"Shapely boundary self-intersection check failed: {e}")
            return False

    def _find_boundary_self_intersection_points(self, geom: QgsGeometry) -> list[tuple[float, float]]:
        """
        Return the deduped (within 1e-6) list of ``(lon, lat)`` boundary
        self-intersection points for ``geom``. Empty list if the boundary is
        simple, the geometry is empty, or any Shapely failure occurs.

        Thin wrapper that converts the QgsGeometry to a Shapely shape and
        delegates to the pure-Python module-level helper
        ``_find_self_intersection_points_in_shape``. See GH-7 / DEC-8.
        """
        if geom is None or geom.isEmpty():
            return []

        try:
            geojson_dict = json.loads(geom.asJson())
            sg = shape(geojson_dict)
            return _find_self_intersection_points_in_shape(sg)
        except Exception as e:
            self._log(f"Shapely self-intersection point finder failed: {e}")
            return []

    def _get_tract_geometry_errors(self, geom: QgsGeometry) -> list[str]:
        """
        Final TRACT-aligned geometry checks. (updated March 2025)
        """
        errors = []

        if geom is None or geom.isEmpty():
            errors.append("Empty geometry")
            return errors

        if QgsWkbTypes.geometryType(geom.wkbType()) != QgsWkbTypes.GeometryType.PolygonGeometry:
            errors.append("Geometry is not polygonal")
            return errors

        if self._has_duplicate_vertices_in_rings(geom):
            errors.append("Duplicated vertices in polygon ring(s)")

        if self._has_rings_with_fewer_than_three_unique_coords(geom):
            errors.append("One or more rings have fewer than three unique coordinates.")

        if self._has_boundary_self_intersections(geom):
            points = self._find_boundary_self_intersection_points(geom)
            errors.append(_format_self_intersection_message(points))

        return errors

